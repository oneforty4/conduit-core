import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  AssetLoader,
  deriveModelMeta,
  parseGlb,
  type AssetEntry,
  type BackendContext,
  type Manifest,
} from '@conduit/assets';
import {
  Bone,
  BoxGeometry,
  Group,
  Mesh,
  MeshPhysicalMaterial,
  MeshStandardMaterial,
  Skeleton,
  SkinnedMesh,
  Texture,
  type BufferGeometry,
  type Material,
  type Object3D,
} from 'three';
import { GLTFLoader, type GLTF } from 'three/addons/loaders/GLTFLoader.js';
import { describe, expect, it, vi, type Mock } from 'vitest';
import { GltfBackend, type GltfAsset } from '../src/index.ts';

const ID = 'ship.sloop';
const URL_PATH = '/assets/ship_sloop.a1b2c3d4.glb';
/**
 * Shared with `@conduit/assets` (docs/render.md §10.2), generated by its `make-glb.ts`. A path, not
 * `new URL(..., import.meta.url)`, which Vite rewrites into a dev-server asset URL.
 */
const FIXTURE = resolve(import.meta.dirname, '../../assets/test/fixtures/ship_sloop.glb');

/** The fixture as an `ArrayBuffer` of this realm (`GLTFLoader.parse` checks `instanceof`). */
function fixtureBytes(): ArrayBuffer {
  const file = readFileSync(FIXTURE);
  const bytes = new Uint8Array(file.byteLength);
  bytes.set(file);
  return bytes.buffer;
}

interface Setup {
  bytes: ArrayBuffer;
  entry: AssetEntry;
  ctx: BackendContext;
  fetch: Mock<(input: RequestInfo | URL, init?: RequestInit) => Promise<Response>>;
}

function setup(): Setup {
  const bytes = fixtureBytes();
  const entry: AssetEntry = {
    type: 'model',
    url: 'ship_sloop.a1b2c3d4.glb',
    hash: `sha256-${'A'.repeat(43)}=`,
    size: bytes.byteLength,
  };
  const manifest: Manifest = {
    version: 1,
    baseUrl: '/assets/',
    assets: { [ID]: entry },
    groups: {},
    regions: {},
  };
  const fetch = vi.fn(async (_input: RequestInfo | URL, _init?: RequestInit) => {
    return new Response(bytes.slice(0));
  });
  const ctx: BackendContext = {
    loader: new AssetLoader(manifest, []),
    id: ID,
    verify: false,
    fetch,
    progress: () => {},
  };
  return { bytes, entry, ctx, fetch };
}

interface Owned {
  geometries: Set<BufferGeometry>;
  materials: Set<Material>;
  textures: Set<Texture>;
}

/** Every geometry, material and material texture reachable from `root`, each once. */
function ownedBy(root: Object3D): Owned {
  const owned: Owned = { geometries: new Set(), materials: new Set(), textures: new Set() };
  root.traverse((node) => {
    const mesh = node as Partial<Mesh>;
    if (mesh.geometry !== undefined) owned.geometries.add(mesh.geometry);
    const material = mesh.material;
    for (const m of Array.isArray(material) ? material : material ? [material] : []) {
      owned.materials.add(m);
      for (const value of Object.values(m)) {
        if ((value as Texture | null)?.isTexture === true) owned.textures.add(value as Texture);
      }
    }
  });
  return owned;
}

/** Spies on `dispose` of everything in `owned`. */
function spyDispose(owned: Owned): { calls(): number[] } {
  const spies = [...owned.geometries, ...owned.materials, ...owned.textures].map((o) =>
    vi.spyOn(o, 'dispose'),
  );
  return { calls: () => spies.map((s) => s.mock.calls.length) };
}

describe('GltfBackend', () => {
  it('load returns the parsed scene with the root node, its clips and meta = deriveModelMeta', async () => {
    const { bytes, entry, ctx, fetch } = setup();
    const backend = new GltfBackend();
    expect(backend.type).toBe('model');
    const signal = new AbortController().signal;
    const asset: GltfAsset = await backend.load(URL_PATH, entry, signal, ctx);

    expect(fetch).toHaveBeenCalledTimes(1);
    expect(fetch.mock.calls[0]?.[0]).toBe(URL_PATH);
    expect(fetch.mock.calls[0]?.[1]?.signal).toBe(signal);
    expect(asset.scene.children.map((c) => c.name)).toEqual(['ship_sloop']);
    const root = asset.scene.children[0]!;
    expect(root.children.map((c) => c.userData['name'])).toEqual([
      'ship_sloop_LOD0',
      'ship_sloop_LOD1',
      'ship_sloop_LOD2',
      'ship_sloop_COL_box',
      'ship_sloop_COL_sphere',
      'ship_sloop_COL_capsule',
      'ship_sloop_COL_convex.001',
      'deck',
      'SOCKET_helm',
    ]);
    // GLTFLoader sanitises names ('.' dropped), which is why ModelBinder matches userData.name.
    expect(root.children[6]?.name).toBe('ship_sloop_COL_convex001');
    expect(asset.animations.map((clip) => clip.name)).toEqual(['idle', 'sail']);
    expect(asset.animations[0]?.tracks.map((t) => t.name)).toEqual(['deck.position']);
    expect(asset.meta).toEqual(deriveModelMeta(parseGlb(bytes, { jsonOnly: true }).json, ID));
    expect(asset.meta.lods.map((l) => l.distance)).toEqual([0, 50, 200]);
  });

  it('dispose disposes every geometry, material and texture exactly once, shared ones included', async () => {
    const { entry, ctx } = setup();
    const backend = new GltfBackend();
    const asset = await backend.load(URL_PATH, entry, new AbortController().signal, ctx);
    const parsed = ownedBy(asset.scene);
    expect(parsed.geometries.size).toBe(7); // one per mesh: the fixture shares no accessors
    expect(parsed.materials.size).toBe(2); // `hull` shared by the LODs, `collider` by the colliders

    // Textures in several slots, one shared by two materials, and a multi-material mesh.
    const shared = new Texture();
    const hull = [...parsed.materials][0] as MeshStandardMaterial;
    hull.map = shared;
    hull.roughnessMap = new Texture();
    const physical = new MeshPhysicalMaterial({ map: shared, clearcoatNormalMap: new Texture() });
    asset.scene.add(new Mesh(new BoxGeometry(), [physical, hull]));
    const owned = ownedBy(asset.scene);
    expect([owned.geometries.size, owned.materials.size, owned.textures.size]).toEqual([8, 3, 3]);
    const spies = spyDispose(owned);

    backend.dispose(asset);
    expect(spies.calls()).toEqual(spies.calls().map(() => 1));
  });

  it('dispose frees each skeleton once, including one shared by two skinned meshes', () => {
    const scene = new Group();
    const bone = new Bone();
    const geometry = new BoxGeometry();
    const material = new MeshStandardMaterial();
    const body = new SkinnedMesh(geometry, material);
    const twin = new SkinnedMesh(geometry, material);
    scene.add(bone, body, twin);
    const skeleton = new Skeleton([bone]);
    body.bind(skeleton);
    twin.bind(skeleton);
    const spies = [skeleton, geometry, material].map((o) => vi.spyOn(o, 'dispose'));
    const meta = deriveModelMeta({ asset: { version: '2.0' } }, 'rig');
    new GltfBackend().dispose({ scene, animations: [], meta });
    expect(spies.map((spy) => spy.mock.calls.length)).toEqual([1, 1, 1]);
  });

  it('keeps shared resources across loaded template owners until the last dispose', async () => {
    const { entry, ctx } = setup();
    const geometry = new BoxGeometry();
    const texture = new Texture();
    const material = new MeshStandardMaterial({ map: texture });
    const scene = new Group();
    scene.add(new Mesh(geometry, material));
    const parse = vi
      .spyOn(GLTFLoader.prototype, 'parse')
      .mockImplementation((_data, _path, onLoad) =>
        onLoad({ scene: scene.clone(true), animations: [] } as unknown as GLTF),
      );
    const spies = [geometry, texture, material].map((resource) => vi.spyOn(resource, 'dispose'));
    try {
      const backend = new GltfBackend();
      const first = await backend.load(URL_PATH, entry, new AbortController().signal, ctx);
      const second = await backend.load(URL_PATH, entry, new AbortController().signal, ctx);
      backend.dispose(first);
      backend.dispose(first);
      expect(spies.map((spy) => spy.mock.calls.length)).toEqual([0, 0, 0]);
      backend.dispose(second);
      expect(spies.map((spy) => spy.mock.calls.length)).toEqual([1, 1, 1]);
    } finally {
      parse.mockRestore();
    }
  });

  it('an abort during parsing rejects with AbortError and disposes the parsed scene', async () => {
    const { entry, ctx } = setup();
    const abort = new AbortController();
    let parsed: Owned | null = null;
    let spies: { calls(): number[] } | null = null;
    class AbortingLoader extends GLTFLoader {
      override parse(
        data: ArrayBuffer | string,
        path: string,
        onLoad: (gltf: GLTF) => void,
        onError?: (event: ErrorEvent) => void,
      ): void {
        super.parse(
          data,
          path,
          (gltf) => {
            parsed = ownedBy(gltf.scene);
            spies = spyDispose(parsed);
            abort.abort(); // the loader released the asset while GLTFLoader was busy
            onLoad(gltf);
          },
          onError,
        );
      }
    }
    const backend = new GltfBackend({ loader: new AbortingLoader() });
    const error: unknown = await backend.load(URL_PATH, entry, abort.signal, ctx).catch((e) => e);
    expect(error).toBeInstanceOf(DOMException);
    expect((error as DOMException).name).toBe('AbortError');
    expect(parsed).not.toBeNull();
    expect(spies!.calls().length).toBe(9); // 7 geometries + 2 materials
    expect(spies!.calls()).toEqual(spies!.calls().map(() => 1));
  });

  it('an abort before the bytes arrive rejects with AbortError without parsing', async () => {
    const { entry, ctx } = setup();
    const parse = vi.spyOn(GLTFLoader.prototype, 'parse');
    const abort = new AbortController();
    const pending = new GltfBackend().load(URL_PATH, entry, abort.signal, ctx);
    abort.abort();
    const error: unknown = await pending.catch((e) => e);
    expect((error as DOMException).name).toBe('AbortError');
    expect(parse).not.toHaveBeenCalled();
    parse.mockRestore();
  });

  it('a GLB that is not glTF binary rejects before GLTFLoader runs', async () => {
    const { entry, ctx } = setup();
    ctx.fetch = async () => new Response(new TextEncoder().encode('not a glb at all'));
    const parse = vi.spyOn(GLTFLoader.prototype, 'parse');
    await expect(
      new GltfBackend().load(URL_PATH, entry, new AbortController().signal, ctx),
    ).rejects.toMatchObject({ name: 'GlbParseError', code: 'bad_magic' });
    expect(parse).not.toHaveBeenCalled();
    parse.mockRestore();
  });
});
